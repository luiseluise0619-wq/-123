FILES = []
for d in ['frontend/logic', 'frontend/screens', 'frontend/locales']:
    for f in sorted(os.listdir(d)):
        if f.endswith(('.js', '.html', '.json')):
            FILES.append(os.path.join(d, f))
FILES.append('frontend/app-logic.js')

hits = {}
for path in FILES:
    s = io.open(path, encoding='utf-8').read()
    orig = s
    for a, b in R:
        if a in s:
            hits[a] = hits.get(a, 0) + s.count(a)
            s = s.replace(a, b)
    if s != orig:
        io.open(path, 'w', encoding='utf-8').write(s)
        print('수정', path)

missed = [a for a, _ in R if a not in hits]
print('\n적용', len(R) - len(missed), '/', len(R))
for m in missed:
    print('  못 찾음:', m[:70])
